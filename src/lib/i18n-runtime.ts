export function translateRuntime(
  language: Language,
  key: RuntimeMessageKey,
  params: Record<string, number | string> = {},
): string {
  return runtimeMessages[language][key].replace(
    /\{(\w+)\}/g,
    (match, name: string) =>
      params[name] === undefined ? match : String(params[name]),
  )
}
